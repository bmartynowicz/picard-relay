import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,readFile,readdir,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {buildLanding} from '../examples/landing/build-static.mjs';
import {relayAddress} from '../examples/landing/setup-flow.mjs';

test('public landing contains only browser files and works under a repository subpath',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'picard-public-landing-'));
 try{
  const sourceSha='a'.repeat(40),result=await buildLanding({outputDir:dir,sourceSha});
  assert.deepEqual((await readdir(dir)).filter(n=>!/^oracle-host-[a-f0-9]{64}\.tgz$/.test(n)&&n!=='oracle-stack.zip').sort(),['.nojekyll','build.json','console.css','index.html','landing.css','landing.js','mark.svg','setup-flow.js','learning-guide.js','public-test.js','social-preview.png'].sort());
  const html=await readFile(join(dir,'index.html'),'utf8');
  assert.ok(!html.includes('<!-- PICARD_'));assert.ok(!html.includes('Local setup concept'));
  assert.ok(html.includes('Your server. Your workspace.'));
  assert.ok(html.includes('connect-src https://picard-relay.141-148-50-78.sslip.io;'));assert.ok(html.includes('name="referrer" content="no-referrer"'));
  const base='https://example.github.io/picard-relay/';
  for(const asset of ['mark.svg','console.css','landing.css','landing.js']){
   assert.ok(html.includes('"./'+asset+'"'));
   assert.equal(new URL('./'+asset,base).pathname,'/picard-relay/'+asset);
  }
  assert.ok((await readFile(join(dir,'landing.js'),'utf8')).includes("from './setup-flow.js'"));
  assert.ok((await readFile(join(dir,'landing.js'),'utf8')).includes("from './learning-guide.js'"));
  assert.ok((await readFile(join(dir,'public-test.js'),'utf8')).includes("from './learning-guide.js'"));
  assert.ok(html.includes('data-panel="guide"'));assert.ok(html.includes('Practice · no AI call'));
  assert.ok(html.includes('Text guide ↗'));assert.ok(html.includes('Sample answer · not generated by AI'));
  assert.ok((await readFile(join(dir,'landing.css'),'utf8')).includes("url('./mark.svg')"));
  const manifest=JSON.parse(await readFile(join(dir,'build.json'),'utf8'));
  assert.equal(manifest.sourceSha,sourceSha);
  const oracleLink=html.match(/href="(https:\/\/cloud\.oracle\.com\/resourcemanager\/stacks\/create\?zipUrl=[^"]+)"/)[1];
  const zipUrl=new URL(oracleLink).searchParams.get('zipUrl');
  assert.equal(zipUrl,'https://github.com/bmartynowicz/picard-relay/releases/download/oracle-launch-'+manifest.files['oracle-stack.zip'].sha256.slice(0,16)+'/oracle-stack.zip');
  assert.ok(!zipUrl.includes('github.io'));
  for(const [name,evidence] of Object.entries(manifest.files)){
   const bytes=await readFile(join(dir,name));assert.equal(bytes.length,evidence.bytes);
   assert.equal(createHash('sha256').update(bytes).digest('hex'),evidence.sha256);
  }
  // The image is metadata-only: ordinary visits do not download it.
  assert.ok(result.totalBytes-manifest.files['social-preview.png'].bytes-Object.entries(manifest.files).filter(([n])=>n==='oracle-stack.zip'||n.endsWith('.tgz')).reduce((n,[,f])=>n+f.bytes,0)<105000);
  const image=await readFile(join(dir,'social-preview.png'));
  assert.equal(image.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
  assert.equal(image.readUInt32BE(16),1280);assert.equal(image.readUInt32BE(20),640);
  assert.ok(image.length<1000000);
  const website='https://bmartynowicz.github.io/picard-relay/';
  assert.ok(html.includes('<link rel="canonical" href="'+website+'">'));
  for(const attr of ['property="og:image"','name="twitter:image"'])assert.ok(html.includes('<meta '+attr+' content="'+website+'social-preview.png">'));
  assert.ok(html.includes('property="og:url" content="'+website+'"'));
  assert.ok(html.includes('name="twitter:card" content="summary_large_image"'));
  assert.ok(!html.includes('<img src="'+website+'social-preview.png"'));
 }finally{await rm(dir,{recursive:true,force:true});}
});

test('publication refuses to overwrite existing output or accept a false source identity',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'picard-public-landing-'));
 try{
  await writeFile(join(dir,'keep.txt'),'preserve');
  await assert.rejects(buildLanding({outputDir:dir}),/landing_output_not_empty/);
  assert.equal(await readFile(join(dir,'keep.txt'),'utf8'),'preserve');
  await assert.rejects(buildLanding({outputDir:dir,sourceSha:'main'}),/landing_source_sha/);
 }finally{await rm(dir,{recursive:true,force:true});}
});

test('public relay entry only navigates to a plain HTTPS origin',()=>{
 assert.equal(relayAddress(' https://relay.example '),'https://relay.example/#overview');
 for(const address of ['http://relay.example','https://owner:secret@relay.example','https://relay.example/private','https://relay.example/?key=secret','https://relay.example/#secret','javascript:alert(1)','bad address'])assert.throws(()=>relayAddress(address));
});
